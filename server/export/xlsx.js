// Excel (.xlsx) writer, using the exceljs package.
const ExcelJS = require('exceljs');
const { manilaWallClock } = require('../utils/manila');

// Each theme's --brand-primary (the same hex values as client/src/index.css), so the header row of
// the file matches the colour theme the librarian chose in Settings → Appearance.
const BRAND_PRIMARY = {
  'nu-classic': '3D398C', cobalt: '0047AB', 'royal-amethyst': '5B2A86', 'heritage-green': '1F4D43',
  'crimson-scholar': '9B1C31', 'midnight-navy': '1B2A49', 'teal-harbor': '0F5E66', 'slate-minimal': '334155',
};

const NUM_FMT = { date: 'yyyy-mm-dd', datetime: 'yyyy-mm-dd hh:mm', percent: '0%', number: '0' };

// Converts a value for an Excel cell. Dates become REAL date cells (sortable/filterable in Excel)
// showing Manila time. Text stays text: exceljs writes strings as plain text cells, never as
// formulas, so a value like "=1+1" is NOT run when the file is opened.
function cellValue(value, type) {
  if (value === null || value === undefined || value === '') return null;
  if (type === 'date' || type === 'datetime') return manilaWallClock(value);
  if (type === 'number' || type === 'percent') return Number(value);
  return String(value);
}

// info = { title, generatedAt, generatedBy, scope, filters: [..], count, theme }
async function toXlsx(columns, rows, info) {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'Stacks Library';
  wb.created = new Date();

  // ----- Sheet 1: the data -----
  const ws = wb.addWorksheet(info.sheetName, {
    views: [{ state: 'frozen', ySplit: 1 }], // the header row stays visible while scrolling
  });
  ws.columns = columns.map((c) => ({ header: c.header, width: c.width || 14 }));
  for (const row of rows) ws.addRow(columns.map((c) => cellValue(c.get(row), c.type)));

  // Number/date formats per column, and long text wraps instead of spilling over
  columns.forEach((c, i) => {
    const col = ws.getColumn(i + 1);
    if (NUM_FMT[c.type]) col.numFmt = NUM_FMT[c.type];
    if (c.width >= 36) col.alignment = { wrapText: true, vertical: 'top' };
  });

  const header = ws.getRow(1);
  const fill = `FF${BRAND_PRIMARY[info.theme] || BRAND_PRIMARY['nu-classic']}`; // ARGB: FF = fully opaque
  header.height = 22;
  header.eachCell((cell) => {
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: fill } };
    cell.alignment = { vertical: 'middle', wrapText: true };
  });
  // Filter dropdowns on every header cell
  ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: columns.length } };

  // ----- Sheet 2: "Report info" (what this file is and how it was made) -----
  const meta = wb.addWorksheet('Report info');
  meta.columns = [{ width: 18 }, { width: 70 }];
  const lines = [
    ['Report', info.title],
    ['Generated at', `${info.generatedAt} (Asia/Manila)`],
    ['Generated by', info.generatedBy],
    ['Scope', info.scopeLabel],
    ['Filters', info.filters.length ? info.filters.join('\n') : 'None'],
    ['Rows', info.count],
  ];
  lines.forEach(([k, v]) => {
    const r = meta.addRow([k, v]);
    r.getCell(1).font = { bold: true };
    r.getCell(2).alignment = { wrapText: true, vertical: 'top', horizontal: 'left' };
  });

  return Buffer.from(await wb.xlsx.writeBuffer());
}

module.exports = { toXlsx };
